        // Короткая запись для создания варианта ответа без повторения конструктора.
        private static ChoiceDefinition Choice(
            string label,
            string consequence,
            StoryFlag[] flags = null,
            FinalAction final = FinalAction.None,
            StoryFlag? requiredFlag = null)
        {
            return new ChoiceDefinition(label, consequence, flags, final, requiredFlag);
        }

        // Короткая запись для звонка; здесь же назначается таймер нужной ночи.
        private static CallDefinition Call(
            int number,
            int night,
            string time,
            string callSign,
            string speaker,
            string transcript,
            string clue,
            params ChoiceDefinition[] choices)
        {
            // Давление растёт каждую ночь: без таймера, затем 30 и 15 секунд.
            float patience = night == 1 ? 0f : night == 2 ? 30f : 15f;
            return new CallDefinition(number, night, time, callSign, speaker, transcript, clue, patience, choices);
        }

